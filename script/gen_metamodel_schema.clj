;; Regenerate src/com/trustblocks/concerto/metamodel_schema.cljc from the
;; metamodel's own CTO, which ships with @accordproject/concerto-metamodel:
;;
;;   clojure -M script/gen_metamodel_schema.clj PATH/TO/metamodel.cto
;;
;; The output lists, for every class in concerto.metamodel@1.0.0, the property
;; names an AST node of that class may carry -- its own and its supertypes'.
(require '[clojure.java.io :as io]
         '[clojure.pprint :as pp]
         '[com.trustblocks.concerto.metamodel :as mm]
         '[com.trustblocks.concerto.parser :as parser])

(let [[path] *command-line-args*
      model  (parser/parse-string (slurp path))
      reg    (mm/registry [model])
      props  (into (sorted-map)
                   (for [d (:declarations model)
                         :let [fqn (str (:namespace model) "." (:name d))]]
                     [(:name d)
                      (vec (sort (into #{"$class"}
                                       (for [f (mm/super-chain reg fqn)
                                             p (:properties (get-in reg [f :declaration]))]
                                         (:name p)))))]))]
  (spit "src/com/trustblocks/concerto/metamodel_schema.cljc"
        (str "(ns com.trustblocks.concerto.metamodel-schema\n"
             "  \"GENERATED by script/gen_metamodel_schema.clj from concerto-metamodel's\n"
             "  metamodel.cto (Apache-2.0): the properties an AST node of each\n"
             "  concerto.metamodel@1.0.0 class may carry, inherited ones included. Do not edit.\")\n\n"
             "(def properties\n  "
             (with-out-str (pp/pprint props))
             ")\n"))
  (println (count props) "classes"))
