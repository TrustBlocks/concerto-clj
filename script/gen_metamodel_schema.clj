;; Regenerate src/com/trustblocks/concerto/metamodel_schema.cljc from the
;; metamodel's own CTO, which ships with @accordproject/concerto-metamodel:
;;
;;   clojure -M script/gen_metamodel_schema.clj PATH/TO/metamodel.cto
;;
;; Two things come out, both for `model-check`'s :metamodelValidation:
;;
;;   form        the Malli schema this library's own compiler produces for
;;               concerto.metamodel@1.0.0.Model -- so a model AST is validated
;;               as the instance of the metamodel that it is.
;;   properties  class -> property -> [declared-type array?], supertypes'
;;               properties included. Malli says *that* a node is wrong; Concerto's
;;               messages name the declared type (`Boolean`, `Declaration`), which a
;;               schema over concrete subtypes cannot recover.
;;
;; One thing is left out on purpose. Three `name` properties carry the identifier
;; regex with JavaScript's `u` flag, which the compiler refuses because the JVM
;; and JavaScript do not agree on its meaning. model-check checks identifiers
;; itself, with the same pattern, before the metamodel is consulted, so the
;; validators are dropped here and reported below.
(require '[clojure.pprint :as pp]
         '[com.trustblocks.concerto.malli :as cm]
         '[com.trustblocks.concerto.metamodel :as mm]
         '[com.trustblocks.concerto.parser :as parser])

(def ^:private dropped (atom 0))

(defn- u-regex? [x]
  (and (map? x)
       (= "StringRegexValidator" (mm/metamodel-type (:$class x)))
       (re-find #"u" (str (:flags x)))))

(defn- drop-u-regexes
  "A validator is a property of its field; remove the ones that are u-flag regexes."
  [x]
  (cond
    (map? x)    (into {}
                      (keep (fn [[k v]]
                              (if (u-regex? v)
                                (do (swap! dropped inc) nil)
                                [k (drop-u-regexes v)])))
                      x)
    (vector? x) (mapv drop-u-regexes x)
    :else       x))

(let [[path] *command-line-args*
      model  (drop-u-regexes (parser/parse-string (slurp path)))
      reg    (mm/registry [model])
      root   "concerto.metamodel@1.0.0.Model"
      form   (cm/->edn reg root)
      props  (into (sorted-map)
                   (for [d (:declarations model)
                         :let [fqn (str (:namespace model) "." (:name d))]]
                     [(:name d)
                      (into (sorted-map "$class" ["String" false])
                            (for [f (reverse (mm/super-chain reg fqn))
                                  p (:properties (get-in reg [f :declaration]))]
                              [(:name p) [(or (:name (:type p))
                                              (mm/metamodel-type (:$class p))
                                              "?")
                                          (boolean (:isArray p))]]))]))
      ;; Primitive properties are named by their metamodel kind; show Concerto's name.
      pretty {"StringProperty" "String" "BooleanProperty" "Boolean" "IntegerProperty" "Integer"
              "LongProperty" "Long" "DoubleProperty" "Double" "DateTimeProperty" "DateTime"}
      props  (update-vals props (fn [m] (update-vals m (fn [[t a]] [(get pretty t t) a]))))]
  (spit "src/com/trustblocks/concerto/metamodel_schema.cljc"
        (str "(ns com.trustblocks.concerto.metamodel-schema\n"
             "  \"GENERATED by script/gen_metamodel_schema.clj from concerto-metamodel's\n"
             "  metamodel.cto (Apache-2.0). Do not edit.\n\n"
             "  `form` is a Malli schema (as EDN, read back with `malli/registry*`) for a\n"
             "  concerto.metamodel@1.0.0.Model, compiled by this library's own compiler.\n"
             "  `properties` maps each metamodel class to its properties -- inherited ones\n"
             "  included -- and their declared types, for Concerto's error messages.\")\n\n"
             "(def properties\n  "
             (with-out-str (pp/pprint props))
             ")\n\n(def form\n  '"
             (with-out-str (pp/pprint form))
             ")\n"))
  (println (count props) "classes;" @dropped "u-flag regex validators dropped;"
           (count (pr-str form)) "chars of schema"))
